# One-off: compiles Curl.hlsl into byte arrays (CurlShaders.h) with the Windows SDK's fxc.
# Re-run only after changing Curl.hlsl, and commit both files:
#   powershell -ExecutionPolicy Bypass -File src\skeuomorph\compile-shaders.ps1
$ErrorActionPreference = "Stop"
$fxc = (Get-ChildItem "C:\Program Files (x86)\Windows Kits\10\bin\*\x64\fxc.exe" | Sort-Object FullName | Select-Object -Last 1).FullName
if (-not $fxc) {
    throw "fxc.exe not found: install the Windows SDK"
}
$dir = $PSScriptRoot
$vs = Join-Path $dir "vs.tmp"
$ps = Join-Path $dir "ps.tmp"
& $fxc /nologo /T vs_4_0 /E VS /O3 /Vn gCurlVS /Fh $vs (Join-Path $dir "Curl.hlsl")
if ($LASTEXITCODE -ne 0) { throw "fxc failed on VS" }
& $fxc /nologo /T ps_4_0 /E PS /O3 /Vn gCurlPS /Fh $ps (Join-Path $dir "Curl.hlsl")
if ($LASTEXITCODE -ne 0) { throw "fxc failed on PS" }
$head = @(
    "// Generated by compile-shaders.ps1 from Curl.hlsl. Don't edit; re-run the script.",
    "// clang-format off"
)
$body = Get-Content $vs, $ps
$tail = @("// clang-format on")
$head + $body + $tail | Set-Content -Encoding ascii (Join-Path $dir "CurlShaders.h")
Remove-Item $vs, $ps
